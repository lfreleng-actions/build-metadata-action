// Conflicting signals keep the existing priority (declaration, then pnpm,
// Yarn, npm, Bun lockfiles) and say so.
func TestPackageManagerConflicts(t *testing.T) {
	tests := []struct {
		name         string
		files        map[string]string
		want         packageManager
		wantWarnings []string // substrings, one per expected warning
	}{
		{
			name: "pnpm and npm lockfiles",
			files: map[string]string{
				"package.json":      `{"name": "t"}`,
				"pnpm-lock.yaml":    "lockfileVersion: '9.0'\n",
				"package-lock.json": `{}`,
			},
			want:         packageManager{name: "pnpm", lockFile: "pnpm-lock.yaml"},
			wantWarnings: []string{"more than one package manager are present (pnpm-lock.yaml, package-lock.json); reporting pnpm"},
		},
		{
			name: "yarn and bun lockfiles",
			files: map[string]string{
				"package.json": `{"name": "t"}`,
				"yarn.lock":    berryYarnLock,
				"bun.lock":     `{}`,
			},
			want:         packageManager{name: "yarn-berry", lockFile: "yarn.lock"},
			wantWarnings: []string{"(yarn.lock, bun.lock); reporting yarn-berry"},
		},
		{
			name: "field disagrees with lockfile",
			files: map[string]string{
				"package.json":      `{"name": "t", "packageManager": "pnpm@9.15.0"}`,
				"package-lock.json": `{}`,
			},
			want: packageManager{name: "pnpm", version: "9.15.0"},
			wantWarnings: []string{
				"packageManager names pnpm but no pnpm lockfile is present (found package-lock.json); reporting pnpm",
			},
		},
		{
			name: "devEngines disagrees with lockfile",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "bun"}}}`,
				"yarn.lock":    classicYarnLock,
			},
			want:         packageManager{name: "bun"},
			wantWarnings: []string{"devEngines.packageManager names bun but no bun lockfile is present"},
		},
		{
			name: "field matches one of several lockfiles",
			files: map[string]string{
				"package.json":      `{"name": "t", "packageManager": "yarn@4.5.0"}`,
				"yarn.lock":         classicYarnLock,
				"package-lock.json": `{}`,
			},
			want:         packageManager{name: "yarn-berry", version: "4.5.0", lockFile: "yarn.lock"},
			wantWarnings: []string{"(yarn.lock, package-lock.json); reporting yarn-berry"},
		},
		{
			name: "packageManager and devEngines disagree",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "pnpm@10.0.0",` +
					` "devEngines": {"packageManager": {"name": "npm"}}}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want:         packageManager{name: "pnpm", version: "10.0.0", lockFile: "pnpm-lock.yaml"},
			wantWarnings: []string{"packageManager names pnpm, which devEngines.packageManager does not list; using pnpm"},
		},
		{
			name: "devEngines alternative matching the lockfile",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager":` +
					` [{"name": "bun"}, {"name": "yarn", "version": "^4.0.0"}]}}`,
				"yarn.lock": berryYarnLock,
			},
			want: packageManager{name: "yarn-berry", version: "^4.0.0", lockFile: "yarn.lock"},
		},
		{
			name: "Yarn alternative matching a berry lockfile",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager":` +
					` [{"name": "yarn", "version": "1.x"}, {"name": "yarn", "version": "4.x"}]}}`,
				"yarn.lock": berryYarnLock,
			},
			want: packageManager{name: "yarn-berry", version: "4.x", lockFile: "yarn.lock"},
		},
		{
			name: "Yarn alternative matching a classic lockfile",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager":` +
					` [{"name": "yarn", "version": "4.x"}, {"name": "yarn", "version": "1.x"}]}}`,
				"yarn.lock": classicYarnLock,
			},
			want: packageManager{name: "yarn", version: "1.x", lockFile: "yarn.lock"},
		},
		{
			name: "unparsable Yarn alternative does not shadow a matching one",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager":` +
					` [{"name": "yarn", "version": "stable"}, {"name": "yarn", "version": "4.x"}]}}`,
				"yarn.lock": berryYarnLock,
			},
			want: packageManager{name: "yarn-berry", version: "4.x", lockFile: "yarn.lock"},
		},
		{
			name: "build metadata is not mistaken for a Corepack hash",
			files: map[string]string{
				"package.json":   `{"name": "t", "packageManager": "pnpm@10.18.0+build.7"}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want:         packageManager{name: "pnpm", lockFile: "pnpm-lock.yaml"},
			wantWarnings: []string{"packageManager has a version this action cannot report; omitting it"},
		},
		{
			name: "devEngines alternatives without a lockfile use the first",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager":` +
					` [{"name": "bun", "version": "1.2.23"}, {"name": "yarn"}]}}`,
			},
			want: packageManager{name: "bun", version: "1.2.23"},
		},
		{
			name: "packageManager matching a later devEngines alternative",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "yarn@4.5.0", "devEngines": {"packageManager":` +
					` [{"name": "bun"}, {"name": "yarn", "version": "3.x"}, {"name": "yarn", "version": "^4.0.0"}]}}`,
				"yarn.lock": berryYarnLock,
			},
			want: packageManager{name: "yarn-berry", version: "4.5.0", lockFile: "yarn.lock"},
		},
		{
			name: "unsupported devEngines alternative beside a supported one",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager":` +
					` [{"name": "cnpm"}, {"name": "pnpm", "version": "10.x"}]}}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want: packageManager{name: "pnpm", version: "10.x", lockFile: "pnpm-lock.yaml"},
		},
		{
			name: "only unsupported devEngines alternatives",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager": [{"name": "cnpm"}]}}`,
			},
			want:         packageManager{name: "npm"},
			wantWarnings: []string{"devEngines.packageManager names an unsupported package manager; ignoring it"},
		},
		{
			name: "packageManager major outside every devEngines alternative",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "pnpm@8.15.0", "devEngines": {"packageManager":` +
					` [{"name": "pnpm", "version": "9.x"}, {"name": "pnpm", "version": "^10.0.0"}]}}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want:         packageManager{name: "pnpm", version: "8.15.0", lockFile: "pnpm-lock.yaml"},
			wantWarnings: []string{"packageManager names pnpm 8, which devEngines.packageManager does not allow; using pnpm 8"},
		},
		{
			name: "packageManager major outside the devEngines range",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "pnpm@6.6.2",` +
					` "devEngines": {"packageManager": {"name": "pnpm", "version": "10.x"}}}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want: packageManager{name: "pnpm", version: "6.6.2", lockFile: "pnpm-lock.yaml"},
			wantWarnings: []string{
				"packageManager names pnpm 6, which devEngines.packageManager does not allow; using pnpm 6",
			},
		},
		{
			name: "packageManager major below an open devEngines range",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "pnpm@8.15.0",` +
					` "devEngines": {"packageManager": {"name": "pnpm", "version": ">=9"}}}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want:         packageManager{name: "pnpm", version: "8.15.0", lockFile: "pnpm-lock.yaml"},
			wantWarnings: []string{"packageManager names pnpm 8, which devEngines.packageManager does not allow"},
		},
		{
			name: "Yarn classic declared against a Berry devEngines range",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "yarn@1.22.22",` +
					` "devEngines": {"packageManager": {"name": "yarn", "version": "^4.0.0"}}}`,
				"yarn.lock": classicYarnLock,
			},
			want:         packageManager{name: "yarn", version: "1.22.22", lockFile: "yarn.lock"},
			wantWarnings: []string{"packageManager names yarn 1, which devEngines.packageManager does not allow"},
		},
		{
			name: "devEngines range admitting the packageManager major",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "pnpm@9.15.0",` +
					` "devEngines": {"packageManager": {"name": "pnpm", "version": ">=8 <10"}}}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want: packageManager{name: "pnpm", version: "9.15.0", lockFile: "pnpm-lock.yaml"},
		},
		{
			name: "devEngines range this cannot parse is not checked",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "pnpm@9.15.0",` +
					` "devEngines": {"packageManager": {"name": "pnpm", "version": "latest"}}}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want: packageManager{name: "pnpm", version: "9.15.0", lockFile: "pnpm-lock.yaml"},
		},
		{
			name: "wildcard version is not reportable",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "pnpm", "version": "*"}}}`,
			},
			want:         packageManager{name: "pnpm"},
			wantWarnings: []string{"devEngines.packageManager has a version this action cannot report; omitting it"},
		},
		{
			name: "malformed version is not reportable",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "pnpm@01.2.3"}`,
			},
			want:         packageManager{name: "pnpm"},
			wantWarnings: []string{"packageManager has a version this action cannot report; omitting it"},
		},
		{
			name: "tag version is not reportable",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "pnpm", "version": "latest"}}}`,
			},
			want:         packageManager{name: "pnpm"},
			wantWarnings: []string{"devEngines.packageManager has a version this action cannot report; omitting it"},
		},
		{
			name: "both npm lockfiles",
			files: map[string]string{
				"package.json":        `{"name": "t"}`,
				"package-lock.json":   `{}`,
				"npm-shrinkwrap.json": `{}`,
			},
			want: packageManager{name: "npm", lockFile: "npm-shrinkwrap.json"},
		},
		{
			name: "both bun lockfiles",
			files: map[string]string{
				"package.json": `{"name": "t"}`,
				"bun.lockb":    "binary",
				"bun.lock":     `{}`,
			},
			want: packageManager{name: "bun", lockFile: "bun.lock"},
		},
		{
			name: "unsupported manager falls back to the lockfile",
			files: map[string]string{
				"package.json":   `{"name": "t", "packageManager": "cnpm@9.0.0"}`,
				"pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
			},
			want:         packageManager{name: "pnpm", lockFile: "pnpm-lock.yaml"},
			wantWarnings: []string{"packageManager names an unsupported package manager; ignoring it"},
		},
		{
			name: "devEngines entry without a name",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager": {"version": "10.0.0"}}}`,
			},
			want:         packageManager{name: "npm"},
			wantWarnings: []string{"devEngines.packageManager names no package manager; ignoring it"},
		},
		{
			name: "devEngines of the wrong shape",
			files: map[string]string{
				"package.json": `{"name": "t", "devEngines": {"packageManager": "pnpm"}}`,
			},
			want:         packageManager{name: "npm"},
			wantWarnings: []string{"devEngines.packageManager is neither an object nor a list of objects"},
		},
		{
			name: "version that is not reportable",
			files: map[string]string{
				"package.json": `{"name": "t", "packageManager": "yarn@https://example.com/yarn.tgz#sha"}`,
				".yarnrc.yml":  "nodeLinker: node-modules\n",
			},
			want:         packageManager{name: "yarn-berry"},
			wantWarnings: []string{"packageManager has a version this action cannot report; omitting it"},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, warnings := detectProject(t, writeProject(t, tt.files))
			if got != tt.want {
				t.Errorf("got %+v, want %+v", got, tt.want)
			}
			if len(warnings) != len(tt.wantWarnings) {
				t.Fatalf("warnings = %q, want %d matching %q", warnings, len(tt.wantWarnings), tt.wantWarnings)
			}
			for i, want := range tt.wantWarnings {
				if !strings.Contains(warnings[i], want) {
					t.Errorf("warning %d = %q, want it to contain %q", i, warnings[i], want)
				}
			}
		})
	}
}

// A declared Yarn version decides between classic and Berry over what the
// files on disk suggest.
func TestYarnDeclaredVersionWins(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string
		want  string
	}{
		{"classic version beside a yarnrc", map[string]string{
			"package.json": `{"name": "t", "packageManager": "yarn@1.22.22"}`,
			".yarnrc.yml":  "nodeLinker: node-modules\n",
			"yarn.lock":    classicYarnLock,
		}, "yarn"},
		{"berry range in devEngines", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "^4.0.0"}}}`,
		}, "yarn-berry"},
		{"no version, classic lockfile", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn"}}}`,
			"yarn.lock":    classicYarnLock,
		}, "yarn"},
		{"no version, berry lockfile", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn"}}}`,
			"yarn.lock":    berryYarnLock,
		}, "yarn-berry"},
		{"unbounded range falls back to files", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "*"}}}`,
			".yarnrc.yml":  "nodeLinker: node-modules\n",
		}, "yarn-berry"},
		{"range spanning generations falls back to a berry lockfile", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": ">=1"}}}`,
			"yarn.lock":    berryYarnLock,
		}, "yarn-berry"},
		{"range spanning generations falls back to a classic lockfile", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": ">=1"}}}`,
			"yarn.lock":    classicYarnLock,
		}, "yarn"},
		{"alternation spanning generations falls back to files", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "4 || 1"}}}`,
			"yarn.lock":    classicYarnLock,
		}, "yarn"},
		{"lower bound of 2 or more is berry", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": ">=2"}}}`,
			"yarn.lock":    classicYarnLock,
		}, "yarn-berry"},
		{"classic wildcard range is classic", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "1.x"}}}`,
			".yarnrc.yml":  "nodeLinker: node-modules\n",
		}, "yarn"},
		{"upper bound below 2 is classic despite a yarnrc", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "<2"}}}`,
			".yarnrc.yml":  "nodeLinker: node-modules\n",
		}, "yarn"},
		{"bounded classic range is classic despite a berry lockfile", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": ">=1 <2"}}}`,
			"yarn.lock":    berryYarnLock,
		}, "yarn"},
		{"berry alternation is berry despite a classic lockfile", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "^2 || ^4"}}}`,
			"yarn.lock":    classicYarnLock,
		}, "yarn-berry"},
		{"classic hyphen range is classic", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "1.0.0 - 1.22.22"}}}`,
			"yarn.lock":    berryYarnLock,
		}, "yarn"},
		{"unparsable range falls back to files", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "stable"}}}`,
			"yarn.lock":    berryYarnLock,
		}, "yarn-berry"},
		{"empty range falls back to files", map[string]string{
			"package.json": `{"name": "t", "devEngines": {"packageManager": {"name": "yarn", "version": "1.20 - 1.10"}}}`,
			"yarn.lock":    berryYarnLock,
		}, "yarn-berry"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, _ := detectProject(t, writeProject(t, tt.files))
			if got.name != tt.want {
				t.Errorf("name = %q, want %q", got.name, tt.want)
			}
		})
	}
}

