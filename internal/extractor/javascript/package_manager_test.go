func TestPnpmWorkspace(t *testing.T) {
	tests := []struct {
		name           string
		files          map[string]string
		wantWorkspaces []string
	}{
		{
			name: "pnpm-workspace.yaml only",
			files: map[string]string{
				"package.json":        `{"name": "t"}`,
				"pnpm-workspace.yaml": "packages:\n  - packages/*\n  - apps/*\n",
			},
			wantWorkspaces: []string{"packages/*", "apps/*"},
		},
		{
			name: "both sources are merged without duplicates",
			files: map[string]string{
				"package.json":        `{"name": "t", "workspaces": ["packages/*", "tools/*"]}`,
				"pnpm-workspace.yaml": "packages:\n  - packages/*\n  - apps/*\n  - '!**/test/**'\n",
			},
			wantWorkspaces: []string{"packages/*", "tools/*", "apps/*", "!**/test/**"},
		},
		{
			name: "settings without packages",
			files: map[string]string{
				"package.json":        `{"name": "t"}`,
				"pnpm-workspace.yaml": "onlyBuiltDependencies:\n  - esbuild\n",
			},
		},
		{
			name: "malformed pnpm-workspace.yaml",
			files: map[string]string{
				"package.json":        `{"name": "t", "workspaces": ["packages/*"]}`,
				"pnpm-workspace.yaml": "packages: [unclosed\n",
			},
			wantWorkspaces: []string{"packages/*"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			metadata, err := NewExtractor().Extract(writeProject(t, tt.files))
			if err != nil {
				t.Fatal(err)
			}
			isWorkspace, _ := metadata.LanguageSpecific["is_workspace"].(bool)
			if isWorkspace != (len(tt.wantWorkspaces) > 0) {
				t.Errorf("is_workspace = %t, want %t", isWorkspace, len(tt.wantWorkspaces) > 0)
			}
			workspaces, _ := metadata.LanguageSpecific["workspaces"].([]string)
			if !slices.Equal(workspaces, tt.wantWorkspaces) {
				t.Errorf("workspaces = %q, want %q", workspaces, tt.wantWorkspaces)
			}
			if len(tt.wantWorkspaces) > 0 && metadata.LanguageSpecific["workspace_count"] != len(tt.wantWorkspaces) {
				t.Errorf("workspace_count = %v, want %d", metadata.LanguageSpecific["workspace_count"], len(tt.wantWorkspaces))
			}
		})
	}
}

