const (
	classicYarnLock = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n" +
		"# yarn lockfile v1\n\n\nleft-pad@^1.3.0:\n  version \"1.3.0\"\n"
	berryYarnLock = "# This file is generated by running \"yarn install\" inside your project.\n" +
		"# Manual changes might be lost - proceed with caution!\n\n" +
		"__metadata:\n  version: 8\n  cacheKey: 10c0\n"
)

// writeProject creates a project directory holding files.
func writeProject(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// detectProject runs package manager detection over a project directory.
func detectProject(t *testing.T, dir string) (packageManager, []string) {
	t.Helper()
	content, err := os.ReadFile(filepath.Join(dir, "package.json"))
	if err != nil {
		t.Fatal(err)
	}
	var pkg PackageJSON
	if err := json.Unmarshal(content, &pkg); err != nil {
		t.Fatal(err)
	}
	return detectPackageManager(dir, &pkg)
}

// Every way a project can name its package manager (a lockfile, the
// packageManager field, devEngines.packageManager, or several together)
// must give the same answer.
func TestPackageManagerConsistency(t *testing.T) {
	managers := []struct {
		name     string
		want     string
		version  string
		lockFile string
		files    map[string]string
	}{
		{"npm package-lock", "npm", "10.9.2", "package-lock.json",
			map[string]string{"package-lock.json": `{"lockfileVersion": 3}`}},
		{"npm shrinkwrap", "npm", "10.9.2", "npm-shrinkwrap.json",
			map[string]string{"npm-shrinkwrap.json": `{"lockfileVersion": 3}`}},
		{"yarn classic", "yarn", "1.22.22", "yarn.lock",
			map[string]string{"yarn.lock": classicYarnLock}},
		{"yarn berry with yarnrc", "yarn-berry", "4.5.0", "yarn.lock",
			map[string]string{"yarn.lock": berryYarnLock, ".yarnrc.yml": "nodeLinker: node-modules\n"}},
		{"yarn berry lockfile only", "yarn-berry", "4.5.0", "yarn.lock",
			map[string]string{"yarn.lock": berryYarnLock}},
		{"yarn 2", "yarn-berry", "2.4.3", "yarn.lock",
			map[string]string{"yarn.lock": berryYarnLock}},
		{"pnpm", "pnpm", "10.18.0", "pnpm-lock.yaml",
			map[string]string{"pnpm-lock.yaml": "lockfileVersion: '9.0'\n"}},
		{"bun text lockfile", "bun", "1.2.23", "bun.lock",
			map[string]string{"bun.lock": `{"lockfileVersion": 1}`}},
		{"bun binary lockfile", "bun", "1.1.38", "bun.lockb",
			map[string]string{"bun.lockb": "binary"}},
	}

	declarations := []struct {
		name        string
		packageJSON string // formatted with the manager name and version
		declares    bool
	}{
		{"no declaration", `{"name": "t"}`, false},
		{"packageManager", `{"name": "t", "packageManager": "%[1]s@%[2]s"}`, true},
		{"packageManager with hash", `{"name": "t", "packageManager": "%[1]s@%[2]s+sha512.0123abcd"}`, true},
		{"devEngines object",
			`{"name": "t", "devEngines": {"packageManager": {"name": "%[1]s", "version": "%[2]s"}}}`, true},
		{"devEngines array",
			`{"name": "t", "devEngines": {"packageManager": [{"name": "%[1]s", "version": "%[2]s", "onFail": "error"}]}}`,
			true},
		{"devEngines with hash",
			`{"name": "t", "devEngines": {"packageManager": {"name": "%[1]s", "version": "%[2]s+sha512.0123abcd"}}}`,
			true},
		{"both fields",
			`{"name": "t", "packageManager": "%[1]s@%[2]s",` +
				` "devEngines": {"packageManager": {"name": "%[1]s", "version": "%[2]s"}}}`, true},
	}

	for _, manager := range managers {
		family := strings.TrimSuffix(manager.want, "-berry")
		for _, declared := range declarations {
			for _, withLockFile := range []bool{true, false} {
				if !declared.declares && !withLockFile {
					continue // nothing names a manager; see TestPackageManagerDefault
				}
				name := fmt.Sprintf("%s/%s/lockfile=%t", manager.name, declared.name, withLockFile)
				t.Run(name, func(t *testing.T) {
					packageJSON := declared.packageJSON
					if declared.declares {
						packageJSON = fmt.Sprintf(packageJSON, family, manager.version)
					}
					files := map[string]string{"package.json": packageJSON}
					wantLockFile, wantVersion := "", ""
					if withLockFile {
						maps.Copy(files, manager.files)
						wantLockFile = manager.lockFile
					}
					if declared.declares {
						wantVersion = manager.version
					}

					got, warnings := detectProject(t, writeProject(t, files))
					if got.name != manager.want {
						t.Errorf("name = %q, want %q", got.name, manager.want)
					}
					if got.version != wantVersion {
						t.Errorf("version = %q, want %q", got.version, wantVersion)
					}
					if got.lockFile != wantLockFile {
						t.Errorf("lockFile = %q, want %q", got.lockFile, wantLockFile)
					}
					if len(warnings) > 0 {
						t.Errorf("unexpected warnings: %q", warnings)
					}
				})
			}
		}
	}
}

